"""
tasks/minutes/memory/prompts.py
跨场次记忆提取提示词规范：采用顶级字段物理隔离 decisions (定案决议) 与 actions (行动待办)
"""
from __future__ import annotations

MEMORY_EXTRACTOR_SYSTEM_PROMPT = """你是一个严谨的会议核心资产提炼引擎。
请仔细阅读【本场会议纪要】，严格提取具备跨会议传承价值的事项（定案决议、行动待办、办结项）。
坚决贯彻「宁缺毋滥」原则，严禁提取泛泛讨论、日常职责、探讨建议与非终态观点。
必须严格按照给定的 JSON 格式输出，包含 decisions、actions、close 三个顶级列表。
直接输出纯 JSON 数据，严禁包含任何分析推理过程、解释说明或 Markdown 代码围栏。"""


def build_memory_extractor_user_prompt(minutes_md: str, active_open_items: list[dict]) -> str:
    """构建记忆提取用户提示词，输入本场纪要正文与历史未闭环待办参考清单"""
    items_text = (
        "\n".join(f"- {item.get('memory', '')}" for item in active_open_items[:30])
        if active_open_items
        else "无"
    )
    return f"""==============================
【本场会议纪要】
{minutes_md}
==============================

【参考：历史尚未闭环的行动项（供核对是否有办结进展）】
{items_text}
==============================

【提取规则】

一、定案决议提取（decisions 列表）：
  1. 准入门槛：
     - 会议中达成无异议共识的最终定案、阶段性方案、业务/技术选型口径，以及针对分歧或优先级的明确取舍；
     - 只要作为后续工作的前提或全员遵循的规则，即必须纳入；
     - 仅提取本场会议中新拍板、新定案或发生决策调整的结论；严禁将历史回顾、进展同步中提及的“继续遵循/沿用既往方案推进测试”等既有事实重复提取为新决议；
     - 严禁提取尚无定论的开放式探讨、待调研事项或例行业务常识。
  2. 边界指导（核心原则）：
     - 方案定调归 decision，具体执行动作归 action；
     - 哪怕某项方案指定了具体责任人去跟进落地，该方案的【结论定调本身】依然必须独立作为一条 decision 提取（作为跨场次记忆接力棒）；具体的落地动作则归入 action。
  3. 语言规范：用客观简洁的陈述句概括“定了什么结论/遵循什么规则”，剥离口语废话。决议由团队共同遵循，无需责任人与截止时间。
  4. 数量配额：最多 10 项（按业务影响与约束范围从高到低保留）。

二、行动待办提取（actions 列表）：
  1. 准入门槛：
     - 必须有具体责任人认领，严禁输出责任人为空或泛指（如“团队”、“全员”）的条目；
     - 必须产出客观可检验的交付物（代码上线/压测报告/方案评审），例行岗位职责、日常沟通同步一律不提取；
     - 必须是可在未来特定节点被验收并闭环的专项工作。
  2. 语言规范：使用自然的陈述句清晰表达行动事项与交付目标，语言保持通顺，责任人和截止时间已由独立字段承载。
  3. 目标聚合：同一责任人针对同一目标的连续行动必须整体合并为一条，严禁拆为琐碎碎片。
  4. 数量配额：上限 15 条，按重要性优先级保留。

三、办结事项提取（close 列表，仅针对历史待办，无则返回 []）：
  1. 仅提取本场明确宣告已闭环的历史行动，必须包含终态标志词（已上线 / 达标 / 修复结项）；
  2. 严禁自提自结（本场新提出的待办绝不能出现在 close 中）；
  3. 语言规范：自然陈述办结结论。

【输出 JSON 契约格式】
{{
  "decisions": [
    {{
      "content": "明确陈述拍板定案的结论、技术选型或业务规则（无需责任人）"
    }}
  ],
  "actions": [
    {{
      "content": "使用通顺自然的陈述句描述交付物与行动事项，语义完整",
      "owner": "责任人姓名（必须为具体人员姓名）",
      "deadline": "截止时限原词或 null"
    }}
  ],
  "close": [
    {{
      "content": "自然陈述办结结论、已经结束的历史待办"
    }}
  ]
}}
"""
