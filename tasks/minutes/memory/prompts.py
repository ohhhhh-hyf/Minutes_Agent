"""
tasks/minutes/memory/prompts.py
跨场次记忆提取提示词规范：严格区分 action (行动待办) 与 decision (定案决议)
"""
from __future__ import annotations

MEMORY_EXTRACTOR_SYSTEM_PROMPT = """你是一个严谨的会议核心资产提炼引擎。
请仔细阅读【本场会议纪要】，严格提取具备跨会议传承价值的事项（行动待办、定案决议、办结项）。
坚决贯彻「宁缺毋滥」原则，严禁提取泛泛讨论、日常职责、探讨建议与非终态观点。
直接输出纯 JSON 数据，严禁包含任何分析推理过程、解释说明或 Markdown 代码围栏。"""


def build_memory_extractor_user_prompt(minutes_md: str, active_open_items: list[dict]) -> str:
    """构建记忆提取用户提示词，输入本场纪要正文与历史未闭环待办参考清单"""
    items_text = (
        "\n".join(f"- {item.get('memory', '')}" for item in active_open_items[:30])
        if active_open_items
        else "无"
    )
    return f"""==============================
【本场会议纪要】
{minutes_md}
==============================

【参考：历史尚未闭环的行动项（供核对是否有办结进展）】
{items_text}
==============================

【提取规则】

一、open 资产提取（两类严格区分）：

  类型 A：行动待办（category = "action" ）：
  1. 准入门槛（缺一不可）：
     - 必须有具体责任人认领，严禁输出 owner 为空的条目；
     - 必须产出客观可检验的交付物（代码上线/压测报告/方案评审），例行岗位职责、沟通同步、日常学习反思一律不提取；
     - 必须是可在未来特定节点被验收并闭环的专项工作。
  2. 语言规范：
     - 使用自然的陈述句清晰表达行动事项与交付目标；
     - 语言保持通顺，责任人和截止时间已由独立字段承载。
  3. 目标聚合：同一责任人针对同一目标的连续行动必须整体合并为一条，严禁拆为琐碎碎片；
  4. 数量配额：上限 15 条，按重要性优先级保留。

  类型 B：定案决议（category = "decision" ）：
  1. 准入门槛（坚决遵循宁缺毋滥）：
     - 必须是全会明确拍板、不可逆、具备团队约束力的最终技术选型、架构路线或业务口径裁决；
     - 坚决排除过程探讨：任何“建议考虑”、“倾向于”、“正在调研”、“后续评估”、“大家觉得可以”等未形成最终确定方案的探讨，一律严禁提取！
     - 排除纯执行待办：决议只提取团队共同遵循的方案结论，单纯由某人负责去跑腿落地的动作必须归入 action；
  2. 语言规范：清晰陈述定案结论；
  3. 数量硬限：上限最多 10 项（按重要度保留，若本场无重大拍板决议则不提取任何 decision）。

二、close 办结提取（仅针对历史行动待办，无则返回 []）：
  1. 仅提取本场明确宣告已闭环的历史行动，必须包含终态标志词（已上线 / 达标 / 修复结项）；
  2. 严禁自提自结（本场新提出的待办绝不能出现在 close 中）；
  3. 语言规范：自然陈述办结结论。

【输出 JSON 契约格式】
{{
  "open": [
    {{
      "category": "action 或 decision",
      "content": "事项正文（待办：使用通顺自然的陈述句描述交付物，语义完整；决议：明确陈述拍板定案的结论）",
      "owner": "责任人姓名。action 必填；decision 填 null",
      "deadline": "截止时限原词或 null。decision 填 null"
    }}
  ],
  "close": [
    {{
      "content": "自然陈述办结结论、已经结束的历史待办。"
    }}
  ]
}}"""
